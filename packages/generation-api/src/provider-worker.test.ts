it('poll timeout and restart resume GET only, unknown pauses, reconcile ignores synthetic failure', async () => {
    let creates = 0;
    let polls = 0;
    const ids: string[] = [];
    const provider: GenerationProvider = { bindingId: 'agnes-simulated', create: async () => { creates++; return { externalJobId: 'same-job', status: 'queued' }; }, get: async (id) => {
            ids.push(id);
            polls++;
            if (polls === 1)
                throw Error('secret-timeout');
            return { status: polls === 2 ? 'unknown' : 'failed' };
        }, download: async () => { throw Error('unexpected'); } };
    const s = await setup(provider);
    s.advance();
    await s.worker.tick();
    s.advance();
    await s.worker.tick();
    expect(s.store.read().items[0]?.status).toBe('running');
    const attempt = s.store.read().attempts[0]!;
    expect(Date.parse(attempt.nextPollAt!) - Date.parse(attempt.lastPolledAt!)).toBeGreaterThanOrEqual(100);
    await s.worker.tick();
    expect(polls).toBe(1);
    await s.store.close();
    const reopened = await GenerationStore.open(join(s.dir, 'state'));
    opened.push(reopened);
    const worker = new GenerationWorker(reopened, provider, s.fixtures, undefined, s.clock);
    s.advance();
    await worker.tick();
    expect(reopened.read().items[0]?.status).toBe('needs_reconciliation');
    await worker.tick();
    expect(polls).toBe(2);
    const { reconcileProviderItem } = await import('../../domain/src/provider-commands.js');
    const item = reopened.read().items[0]!;
    const reconciled = await reopened.transact(state => reconcileProviderItem(state, item.id, { expectedVersion: item.version, outcome: 'failure' }, s.clock()));
    expect(reconciled.ok).toBe(true);
    expect(reopened.read().items[0]?.status).toBe('running');
    expect(reopened.read().credits.reserved).toBe(1);
    await worker.tick();
    expect(reopened.read().items[0]?.status).toBe('failed');
    expect(creates).toBe(1);
    expect(ids).toEqual(['same-job', 'same-job', 'same-job']);
});
