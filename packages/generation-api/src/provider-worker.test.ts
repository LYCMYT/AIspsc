it('persists original claim submittedAt before IO and preserves it after ambiguous response', async () => {
    let entered!: () => void;
    let release!: () => void;
    const arrived = new Promise<void>(r => { entered = r; });
    const gate = new Promise<void>(r => { release = r; });
    const provider: GenerationProvider = { bindingId: 'agnes-simulated', create: async () => { entered(); await gate; throw Error('ambiguous'); }, get: async () => ({ status: 'unknown' }), download: async () => { throw Error('unexpected'); } };
    const s = await setup(provider);
    s.advance();
    const claimedAt = new Date(s.clock()).toISOString();
    const ticking = s.worker.tick();
    await arrived;
    const persisted = s.store.read().attempts[0]?.submittedAt;
    s.advance();
    release();
    await ticking;
    expect(persisted).toBe(claimedAt);
    expect(s.store.read().attempts[0]?.submittedAt).toBe(claimedAt);
    expect(s.store.read().items[0]?.status).toBe('needs_reconciliation');
});
